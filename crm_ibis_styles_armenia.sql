CREATE VIEW v_actividad AS
SELECT c.id_cliente,
  COALESCE(SUM(t.nombre='Solicitud de reunión'),0) AS n_solicitud_reunion,
  COALESCE(SUM(t.nombre='Descarga de dossier'),0) AS n_dossier,
  COALESCE(SUM(t.nombre IN ('Asistencia a evento','Visita al proyecto')),0) AS n_asistencia,
  COALESCE(MAX(CASE WHEN t.nombre='Recorrido virtual' THEN i.valor END),0) AS max_recorrido,
  COALESCE(SUM(t.nombre='Intento sin respuesta'),0) AS n_sin_respuesta,
  COALESCE(SUM(t.nombre='Reunión realizada'),0) AS n_reunion_realizada,
  MAX(i.fecha) AS ultima_interaccion
FROM cliente c LEFT JOIN interaccion i ON i.id_cliente=c.id_cliente LEFT JOIN tipo_interaccion t ON t.id_tipo=i.id_tipo
GROUP BY c.id_cliente;
CREATE VIEW v_puntaje AS
SELECT c.id_cliente, c.nombres||' '||c.apellidos AS cliente, s.codigo AS segmento, e.nombre AS etapa, a.ultima_interaccion,
  CASE WHEN a.n_solicitud_reunion>0 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='reunion') ELSE 0 END
 +CASE WHEN r.cumple_capacidad=1 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='capacidad') ELSE 0 END
 +CASE WHEN c.id_canal=(SELECT id_canal FROM canal WHERE nombre='Referidos') OR c.referido_por IS NOT NULL THEN (SELECT puntos FROM criterio_puntaje WHERE clave='referido') ELSE 0 END
 +CASE WHEN a.n_asistencia>0 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='asistencia') ELSE 0 END
 +CASE WHEN a.n_dossier>0 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='dossier') ELSE 0 END
 +CASE WHEN c.experiencia_inmuebles=1 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='experiencia') ELSE 0 END
 +CASE WHEN a.max_recorrido>0.5 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='recorrido') ELSE 0 END
 +CASE WHEN ci.es_objetivo=1 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='ciudad_objetivo') ELSE 0 END
 +CASE WHEN (SELECT COUNT(*) FROM interaccion i2 JOIN tipo_interaccion t2 ON t2.id_tipo=i2.id_tipo
             WHERE i2.id_cliente=c.id_cliente AND t2.nombre='Correo abierto' AND i2.fecha>=date(a.ultima_interaccion,'-30 day'))>=3
       THEN (SELECT puntos FROM criterio_puntaje WHERE clave='correos') ELSE 0 END
 +CASE WHEN a.n_sin_respuesta>=3 THEN (SELECT puntos FROM criterio_puntaje WHERE clave='sin_respuesta') ELSE 0 END AS puntaje,
  c.solicito_baja
FROM cliente c JOIN segmento s ON s.id_segmento=c.id_segmento JOIN etapa e ON e.id_etapa=c.id_etapa
JOIN rango_inversion r ON r.id_rango=c.id_rango JOIN ciudad ci ON ci.id_ciudad=c.id_ciudad JOIN v_actividad a ON a.id_cliente=c.id_cliente;
CREATE VIEW v_clasificacion AS
SELECT p.*, CASE WHEN p.solicito_baja=1 THEN 'Baja'
  WHEN p.puntaje>=(SELECT valor FROM parametro WHERE clave='umbral_caliente') THEN 'Caliente'
  WHEN p.puntaje>=(SELECT valor FROM parametro WHERE clave='umbral_tibio') THEN 'Tibio' ELSE 'Frío' END AS clasificacion
FROM v_puntaje p;
CREATE VIEW v_embudo AS
SELECT orden, etapa, llegaron AS leads_que_llegaron,
  ROUND(1.0*llegaron/LAG(llegaron) OVER (ORDER BY orden),3) AS conversion_real, conversion_meta
FROM (SELECT e.orden, e.nombre AS etapa, e.conversion_meta,
        (SELECT COUNT(*) FROM cliente c JOIN etapa e2 ON e2.id_etapa=c.id_etapa WHERE e2.orden>=e.orden) AS llegaron
      FROM etapa e) ORDER BY orden;
CREATE VIEW v_canal AS
SELECT ca.nombre AS canal, COUNT(c.id_cliente) AS leads,
  SUM(CASE WHEN e.orden>=2 THEN 1 ELSE 0 END) AS calificados,
  SUM(CASE WHEN e.orden=6 THEN 1 ELSE 0 END) AS ventas,
  ROUND(1.0*SUM(CASE WHEN e.orden=6 THEN 1 ELSE 0 END)/COUNT(c.id_cliente),4) AS conversion
FROM canal ca LEFT JOIN cliente c ON c.id_canal=ca.id_canal LEFT JOIN etapa e ON e.id_etapa=c.id_etapa GROUP BY ca.id_canal;
CREATE VIEW v_segmento AS
SELECT s.nombre AS segmento, s.suites_meta, COUNT(c.id_cliente) AS leads,
  SUM(CASE WHEN e.orden>=4 THEN 1 ELSE 0 END) AS reunion_o_mas,
  SUM(CASE WHEN e.orden=6 THEN 1 ELSE 0 END) AS ventas,
  COALESCE((SELECT SUM(o.valor_cop_m) FROM operacion o JOIN cliente c2 ON c2.id_cliente=o.id_cliente
            WHERE c2.id_segmento=s.id_segmento AND o.tipo IN ('Promesa','Escritura')),0) AS valor_vendido_cop_m
FROM segmento s LEFT JOIN cliente c ON c.id_segmento=s.id_segmento LEFT JOIN etapa e ON e.id_etapa=c.id_etapa GROUP BY s.id_segmento;
CREATE VIEW v_campana AS
SELECT ca.nombre AS campana, ca.presupuesto_cop_m, ca.meta_leads, COUNT(c.id_cliente) AS leads_base_ejemplo,
  SUM(CASE WHEN e.orden=6 THEN 1 ELSE 0 END) AS ventas_base_ejemplo, ca.meta_ventas,
  ROUND(1.0*ca.presupuesto_cop_m/ca.meta_ventas,1) AS cac_meta_cop_m
FROM campana ca LEFT JOIN cliente c ON c.id_campana=ca.id_campana LEFT JOIN etapa e ON e.id_etapa=c.id_etapa GROUP BY ca.id_campana;
CREATE VIEW v_inventario AS
SELECT estado, COUNT(*) AS suites, ROUND(SUM(precio_lista_cop_m),1) AS valor_lista_cop_m, ROUND(AVG(precio_lista_cop_m),1) AS precio_promedio_cop_m
FROM unidad GROUP BY estado;
CREATE VIEW v_clasificacion_resumen AS
SELECT clasificacion, COUNT(*) AS registros, ROUND(1.0*COUNT(*)/(SELECT COUNT(*) FROM cliente),3) AS participacion
FROM v_clasificacion GROUP BY clasificacion;
CREATE VIEW v_kpis AS
SELECT 'Leads en la base' AS kpi, COUNT(*) AS valor, (SELECT valor FROM parametro WHERE clave='meta_leads') AS meta FROM cliente
UNION ALL SELECT 'Suites vendidas', COUNT(*), (SELECT valor FROM parametro WHERE clave='meta_ventas') FROM operacion WHERE tipo IN ('Promesa','Escritura')
UNION ALL SELECT 'Conversión lead a venta', ROUND(1.0*(SELECT COUNT(*) FROM operacion WHERE tipo IN ('Promesa','Escritura'))/COUNT(*),4), (SELECT valor FROM parametro WHERE clave='meta_conversion') FROM cliente
UNION ALL SELECT 'Leads por referidos', ROUND(1.0*SUM(CASE WHEN id_canal=(SELECT id_canal FROM canal WHERE nombre='Referidos') THEN 1 ELSE 0 END)/COUNT(*),4), (SELECT valor FROM parametro WHERE clave='meta_referidos') FROM cliente
UNION ALL SELECT 'Clientes con autorización vigente o revocada documentada', ROUND(1.0*(SELECT COUNT(DISTINCT id_cliente) FROM autorizacion_datos)/COUNT(*),4), 1 FROM cliente
UNION ALL SELECT 'Valor vendido (COP millones)', ROUND(COALESCE(SUM(valor_cop_m),0),1), NULL FROM operacion WHERE tipo IN ('Promesa','Escritura');
PRAGMA foreign_keys=ON;

