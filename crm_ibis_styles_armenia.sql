-- 4. Suites disponibles de un piso, con precio de lista
SELECT piso, habitacion, area_m2, precio_lista_cop_m FROM unidad WHERE estado='Disponible' AND piso=8 ORDER BY habitacion;

-- 5. Unidades que despiertan más interés (relación muchos a muchos)
SELECT u.piso, u.habitacion, COUNT(*) AS interesados FROM interes_unidad i JOIN unidad u ON u.id_unidad=i.id_unidad
GROUP BY u.id_unidad ORDER BY interesados DESC LIMIT 10;

-- 6. Clientes que llegaron por referido y quién los refirió (relación consigo misma)
SELECT c.nombres||' '||c.apellidos AS cliente, r.nombres||' '||r.apellidos AS referido_por
FROM cliente c JOIN cliente r ON r.id_cliente=c.referido_por;

-- 7. Clientes que NO se pueden contactar (baja o autorización revocada)
SELECT c.id_cliente, c.nombres, c.apellidos, a.fecha_revocacion FROM cliente c JOIN autorizacion_datos a ON a.id_cliente=c.id_cliente
WHERE c.solicito_baja=1 OR a.vigente=0;

-- 8. Leads calificados sin asesor asignado
SELECT c.id_cliente, c.nombres, c.apellidos, e.nombre AS etapa FROM cliente c JOIN etapa e ON e.id_etapa=c.id_etapa
WHERE c.id_asesor IS NULL AND e.orden>=2;

-- 9. Ventas por asesor
SELECT a.nombre AS asesor, COUNT(*) AS operaciones, ROUND(SUM(o.valor_cop_m),1) AS valor_cop_m
FROM operacion o JOIN asesor a ON a.id_asesor=o.id_asesor GROUP BY a.id_asesor;

-- 10. KPIs contra meta
SELECT * FROM v_kpis;

